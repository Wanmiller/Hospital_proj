"""Run after run_tests_patient.php on an isolated database/server."""
import json
import os
from pathlib import Path
from datetime import date, timedelta
from playwright.sync_api import sync_playwright

if not os.environ.get('HOSPITAL_DB_NAME', '').startswith('hospital_regression_'):
    raise SystemExit('Use a separate hospital_regression_* database.')
BASE = os.environ.get('HOSPITAL_TEST_URL', 'http://127.0.0.1:18000').rstrip('/')
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/patient-preview'
OUT.mkdir(parents=True, exist_ok=True)
KK = json.loads((ROOT/'includes/lang/kk.json').read_text(encoding='utf-8'))
checks = []

def check(ok, name):
    if not ok:
        raise AssertionError(name)
    checks.append(name)
    print('PASS:', name, flush=True)

with sync_playwright() as p:
    browser = p.chromium.launch()
    context = browser.new_context(viewport={'width':1366,'height':960}, locale='kk-KZ')
    page = context.new_page()
    errors, external = [], []
    context.on('page', lambda tab: tab.on('pageerror', lambda error: errors.append(str(error))))
    page.on('pageerror', lambda error: errors.append(str(error)))
    context.on('request', lambda req: external.append(req.url) if not req.url.startswith(BASE) else None)

    def visit(path):
        response = page.goto(BASE+path, wait_until='networkidle')
        check(response.status == 200, 'HTTP page '+path.split('?')[0])
        check(page.locator('html').get_attribute('lang')=='kk', 'Kazakh page '+path.split('?')[0])

    def no_overflow(label):
        check(page.evaluate('document.documentElement.scrollWidth <= innerWidth'), label+' fits viewport')

    visit('/login.php')
    page.get_by_role('link', name=KK['Patient registration'], exact=True).click()
    page.fill('#first_name','Айдана')
    page.fill('#last_name','Тест')
    page.fill('#username','patient_ui')
    page.fill('#phone','+7 700 123 4567')
    page.fill('#dob','2000-01-01')
    page.select_option('#gender','Female')
    page.fill('#password','Patient123!')
    page.fill('#password_confirm','Patient123!')
    page.screenshot(path=str(OUT/'registration.png'),full_page=True)
    no_overflow('Desktop registration')
    page.get_by_role('button', name=KK['Register'],exact=True).click()
    page.wait_for_url('**/login.php')
    check(page.get_by_role('status').is_visible(),'Registration succeeds in browser')
    page.fill('#username','patient_ui')
    page.fill('#password','Patient123!')
    page.get_by_role('button',name=KK['Sign in'],exact=True).click()
    page.wait_for_url('**/patient/dashboard.php')
    check(page.get_by_text(KK['No personal appointments.'],exact=True).is_visible(),'New patient sees empty private dashboard')
    page.get_by_role('link',name=KK['Book appointment'],exact=True).last.click()
    day=(date.today()+timedelta(days=3)).isoformat()
    page.select_option('#doctor_id','1')
    page.fill('#date',day)
    page.get_by_role('button',name=KK['Find available times'],exact=True).click()
    check(page.locator('input[name=time]').count()==16,'Available half-hour slots displayed')
    page.get_by_role('button',name=KK['Confirm booking'],exact=True).click()
    check(page.locator('input[name=time].is-invalid').count()>0,'Required time validation appears')
    page.locator('label:has(input[name=time][value="09:30"])').click()
    check(page.locator('input[name=time][value="09:30"]').is_checked(),'Clicked time is selected correctly')
    check(page.locator('form[method=post]').evaluate('(form) => form.checkValidity()'),'Selecting a time clears radio group validation')
    page.fill('#reason','Жоспарлы тексеру')
    page.screenshot(path=str(OUT/'booking.png'),full_page=True)
    no_overflow('Desktop booking')
    stale=context.new_page()
    stale.goto(page.url,wait_until='networkidle')
    stale.locator('label:has(input[name=time][value="09:30"])').click()
    page.get_by_role('button',name=KK['Confirm booking'],exact=True).click()
    page.wait_for_url('**/patient/dashboard.php')
    check(page.get_by_text('Жоспарлы тексеру',exact=True).is_visible(),'Booking appears on own dashboard')
    stale.get_by_role('button',name=KK['Confirm booking'],exact=True).click()
    check(stale.get_by_role('alert').inner_text()==KK['This doctor already has an appointment at this date and time.'],'Stale slot conflict displayed in Kazakh')
    stale.close()
    page.screenshot(path=str(OUT/'appointments.png'),full_page=True)
    no_overflow('Desktop appointments')
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path=str(OUT/'appointments-mobile.png'),full_page=True)
    no_overflow('Mobile appointments')
    toggle=page.locator('.navbar-toggler')
    toggle.click()
    page.locator('#navbarNav.show').wait_for(state='visible')
    check(page.locator('#navbarNav').is_visible(),'Mobile menu opens')
    toggle.click()
    page.locator('#navbarNav').wait_for(state='hidden')
    check(not page.locator('#navbarNav').is_visible(),'Mobile menu closes')
    page.on('dialog', lambda dialog: dialog.accept())
    page.get_by_role('button',name=KK['Cancel appointment'],exact=True).click()
    page.wait_for_load_state('networkidle')
    check(page.get_by_role('status').is_visible() and page.get_by_text(KK['Cancelled'],exact=True).count()>=1,'Own appointment cancellation works')
    page.select_option('#status','Scheduled')
    page.get_by_role('button',name=KK['Filter'],exact=True).click()
    check(page.get_by_text(KK['No personal appointments.'],exact=True).is_visible(),'Status filter shows empty result after cancellation')
    visit('/patient/book.php?doctor_id=1&date='+day)
    no_overflow('Mobile booking')
    page.locator('input[name=time][value="09:30"]').focus()
    page.keyboard.press('Space')
    check(page.locator('input[name=time][value="09:30"]').is_checked(),'Slot can be selected with keyboard')
    page.screenshot(path=str(OUT/'booking-mobile.png'),full_page=True)
    page.goto(BASE+'/logout.php',wait_until='networkidle')
    check(page.url.endswith('/login.php'),'Patient logout works')
    visit('/register.php')
    no_overflow('Mobile registration')
    page.screenshot(path=str(OUT/'registration-mobile.png'),full_page=True)
    page.set_viewport_size({'width':1366,'height':960})
    visit('/login.php')
    page.fill('#username','admin')
    page.fill('#password','password123')
    page.get_by_role('button',name=KK['Sign in'],exact=True).click()
    page.wait_for_url('**/admin/dashboard.php')
    visit('/admin/users.php')
    page.get_by_role('button',name=KK['Add User'],exact=True).click()
    page.select_option('#u_role','Patient')
    check(page.locator('#patient-card-field').is_visible(),'Admin Patient role shows existing-card selector')
    check(page.locator('#u_patient_id').evaluate('(field) => field.required'),'Existing card is required for admin-created patient')
    page.fill('#u_fname','Тест')
    page.fill('#u_lname','Пациент')
    page.fill('#u_username','patient_admin_ui')
    page.fill('#u_pass','Patient123!')
    page.select_option('#u_patient_id','2')
    page.get_by_role('button',name=KK['Save User'],exact=True).click()
    page.wait_for_load_state('networkidle')
    check(KK['User added successfully.'] in page.get_by_role('alert').inner_text(),'Admin creates patient account for existing card')
    page.locator('form[method=GET] select[name=role]').select_option('Patient')
    page.get_by_role('button',name=KK['Filter'],exact=True).click()
    row=page.locator('tbody tr').filter(has_text='patient_admin_ui')
    check(row.count()==1,'Patient role filter includes newly linked account')
    row.get_by_role('button',name=KK['Edit'],exact=True).click()
    check(page.locator('#u_role').input_value()=='Patient' and not page.locator('#patient-card-field').is_visible(),'Patient edit preserves role and existing link')
    page.get_by_role('button',name=KK['Save User'],exact=True).click()
    page.wait_for_load_state('networkidle')
    check(KK['User updated successfully.'] in page.get_by_role('alert').inner_text(),'Admin saves linked patient without relinking card')
    check(not errors,'No JavaScript errors')
    check(not external,'No external requests for page assets')
    browser.close()

(OUT/'verification.json').write_text(json.dumps({'checks':checks,'count':len(checks)},ensure_ascii=False,indent=2),encoding='utf-8')
print(f'All {len(checks)} browser checks passed.')
